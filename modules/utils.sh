}

info()    { echo -e "  ${G}[+]${NC} $*";  log_raw "  [+] $*"; }
warn()    { echo -e "  ${Y}[!]${NC} $*";  log_raw "  [!] $*"; }
error()   { echo -e "  ${R}[[X]]${NC} $*";  log_raw "  [x] $*"; }
running() { echo -e "  \033[0;36m[→]\033[0m $*";  log_raw "  [→] $*"; }
result()  { echo -e "  ${W}    $*${NC}";  log_raw "    $*"; }
skip()    { echo -e "  ${DIM}[~] $* (skipped)${NC}"; log_raw "  [~] $* (skipped)"; }

log_raw() {
  [ -z "${LOG_FILE:-}" ] && return
  echo "$*" | sed 's/\x1b\[[0-9;]*m//g' >> "$LOG_FILE" 2>/dev/null || true
}

check_tool() {
  local tool="$1"
  if command -v "$tool" &>/dev/null \
    || [[ -x "$HOME/go/bin/$tool" ]] \
    || [[ -x "/home/kali/go/bin/$tool" ]] \
    || [[ -x "/root/go/bin/$tool" ]] \
    || [[ -x "/usr/local/go/bin/$tool" ]] \
    || [[ -x "$HOME/.local/bin/$tool" ]] \
    || [[ -x "/home/kali/.local/bin/$tool" ]] \
    || (command -v python3 &>/dev/null && python3 -c "import $tool" &>/dev/null 2>&1); then
    TOOL_STATUS["$tool"]="available"
    [[ -x "$HOME/go/bin/$tool" ]]          && export PATH="$PATH:$HOME/go/bin"
    [[ -x "/home/kali/go/bin/$tool" ]]     && export PATH="$PATH:/home/kali/go/bin"
    [[ -x "/root/go/bin/$tool" ]]          && export PATH="$PATH:/root/go/bin"
    [[ -x "$HOME/.local/bin/$tool" ]]      && export PATH="$PATH:$HOME/.local/bin"
    [[ -x "/home/kali/.local/bin/$tool" ]] && export PATH="$PATH:/home/kali/.local/bin"
    return 0
  else
    TOOL_STATUS["$tool"]="missing"
    return 1
  fi
}

tool_ok() {
  local t="$1"
  [[ "${TOOL_STATUS[$t]:-missing}" == "available" ]]
}

module_enabled() {
  local mod="$1"
  [[ -z "$ONLY_MODULES" ]] || echo "$ONLY_MODULES" | grep -qw "$mod"
}


# run_step: print [→] label, run cmd, overwrite with [+] label - done (Xs)
run_step() {
  local label="$1"; shift
  local start elapsed
  start=$(date +%s)
  printf "  \033[0;36m[→]\033[0m %s" "$label"
  "$@" >/dev/null 2>&1 || true
  elapsed=$(( $(date +%s) - start ))
  printf "\r\033[2K"
  info "$label - done (${elapsed}s)"
}


run_cmd() {
  local desc="$1"; shift
  local timeout_secs="$1"; shift
  running "$desc"
  local out
  out=$(timeout "$timeout_secs" "$@" 2>&1) || true
  log_raw "$out"
  echo "$out"
}

