section() {
  echo -e "\n${B}╔══════════════════════════════════════════════════════════════╗${NC}"
  echo -e "${B}║${NC}  ${BOLD}${C}$1${NC}"
  echo -e "${B}╚══════════════════════════════════════════════════════════════╝${NC}"
