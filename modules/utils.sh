    elapsed=$((elapsed + interval))
    [[ $elapsed -gt 60 ]] && interval=30

    if [[ $elapsed -ge $limit ]]; then
      kill "$pid" 2>/dev/null || true
      printf "\r\033[2K"
      warn "$label - time limit reached (${limit}s)"
      wait "$pid" 2>/dev/null || true
      return
    fi

    # Update same line with timer
    kill -0 "$pid" 2>/dev/null &&       printf "\r  \033[0;36m[→]\033[0m %s ${DIM}%ds / %ds${NC}\033[K"         "$label" "$elapsed" "$limit"
  done

  wait "$pid" 2>/dev/null || true
  # Overwrite [→] line with [+] done line
  printf "\r\033[2K"
  info "$label - done (${elapsed}s)"
}

# ================================================================
#  DEPENDENCY CHECK
# ================================================================

check_dependencies() {
  echo ""
  echo -e "  ${BOLD}Tool Check${NC}"
  echo -e "  ${DIM}──────────────────────────────────────────────${NC}"

  local required=(dig curl whois openssl python3)
  local optional=(
    "nmap:sudo apt install nmap"
    "theHarvester:sudo apt install theharvester"
    "subfinder:go install github.com/projectdiscovery/subfinder/v2/cmd/subfinder@latest"
    "dnsx:go install github.com/projectdiscovery/dnsx/cmd/dnsx@latest"
    "httpx:go install github.com/projectdiscovery/httpx/cmd/httpx@latest"
    "jq:sudo apt install jq"
    "whatweb:sudo apt install whatweb"
    "wafw00f:sudo apt install wafw00f"
    "wpscan:sudo apt install wpscan"
    "gau:go install github.com/lc/gau/v2/cmd/gau@latest"
    "waybackurls:go install github.com/tomnomnom/waybackurls@latest"
    "dirsearch:pip3 install dirsearch"
  )
  local missing_required=()

  # Required tools
  echo -e "  ${DIM}Required:${NC}"
  for t in "${required[@]}"; do
    if check_tool "$t"; then
      printf "    ${G}✓${NC} %-20s ${DIM}ready${NC}\n" "$t"
    else
      printf "    ${R}✗${NC} %-20s ${R}MISSING${NC}\n" "$t"
      missing_required+=("$t")
    fi
  done

  echo ""
  echo -e "  ${DIM}Optional:${NC}"
  local ok_count=0 miss_count=0
  for entry in "${optional[@]}"; do
    local t="${entry%%:*}"
    local install_hint="${entry#*:}"
    if check_tool "$t"; then
      printf "    ${G}✓${NC} %-20s\n" "$t"
      ((ok_count++))
    else
      printf "    ${R}✗${NC} %-20s ${DIM}# %s${NC}\n" "$t" "$install_hint"
      ((miss_count++))
    fi
  done

  echo ""
  echo -e "  ${DIM}──────────────────────────────────────────────${NC}"
  echo -e "  ${G}$ok_count tools ready${NC}  ${DIM}$miss_count optional missing${NC}"
  echo ""

  if [ ${#missing_required[@]} -gt 0 ]; then
    echo -e "  ${R}Required tools missing: ${missing_required[*]}${NC}"
    echo -e "  Install: ${Y}sudo apt install dnsutils curl whois openssl python3${NC}\n"
    exit 1
  fi
}

# ================================================================
#  INTERACTIVE INPUT
# ================================================================

interactive_input() {
  banner
  check_dependencies
  echo -e "${B}┌─────────────────────────────────────────────────────────────┐${NC}"
  echo -e "${B}│${NC}  ${BOLD}Target Configuration${NC}"
  echo -e "${B}└─────────────────────────────────────────────────────────────┘${NC}\n"

  echo -e "  ${C}[1]${NC} ${BOLD}Target Domain${NC} ${DIM}(e.g. example.com - leave blank to skip)${NC}"
  echo -ne "      ${Y}Domain: ${NC}"
  read -r input_domain
  DOMAIN="${input_domain//[[:space:]]/}"

  if [[ -z "$DOMAIN" && -z "$IP" ]]; then
    error "You must provide at least a domain."
    exit 1
  fi

  if [[ -n "$DOMAIN" && -z "$IP" ]]; then
    IP=$(dig +short A "$DOMAIN" @1.1.1.1 2>/dev/null | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true)
    if [[ -n "$IP" ]]; then
      info "Auto-resolved IP: ${W}$IP${NC}"
    fi
    # Note: IP may still be resolved later via DNS module — no warning needed here
  fi

  echo -e "\n  ${C}[2]${NC} ${BOLD}Scan Mode${NC}"
  echo -e "      ${DIM}[1] Full scan (passive + active) ~25 min — WHOIS, DNS, TLS, subdomains, nmap, dirsearch, WPScan, JS secrets...${NC}"
  echo -e "      ${DIM}[2] Passive only ~12 min — WHOIS, DNS, TLS, subdomains, JS, leaks, Shodan (no active probing)${NC}"
  echo -e "      ${DIM}[3] Quick mode ~2 min — WHOIS, DNS, TLS, headers only${NC}"
  echo -ne "      ${Y}Choice: ${NC}"
  read -r scan_mode_input
  scan_mode_input="${scan_mode_input:-1}"
  printf "\033[1A\033[2K      ${Y}Choice [${scan_mode_input}]${NC}\n"

  case "$scan_mode_input" in
    2) ACTIVE=false ;;
    3) QUICK=true; ACTIVE=false ;;
  esac

  if ! $QUICK; then
    echo -e "\n  ${C}[3]${NC} ${BOLD}Subdomain Wordlist${NC} ${DIM}(Enter = use default)${NC}"
    echo -e "      ${DIM}Default: ${WORDLIST_SUB}${NC}"
    echo -ne "      ${Y}Custom subdomain wordlist (or Enter to skip): ${NC}"
    read -r wl_sub
    [[ -n "$wl_sub" ]] && WORDLIST_SUB="$wl_sub"

    echo -e "\n  ${C}[4]${NC} ${BOLD}Thread Count${NC} ${DIM}(default: 50)${NC}"
    echo -ne "      ${Y}Threads [${THREADS}]: ${NC}"
    read -r t_input
    [[ -n "$t_input" ]] && THREADS="$t_input"

    echo -e "\n  ${C}[5]${NC} ${BOLD}API Keys${NC} ${DIM}(optional - press Enter to skip)${NC}"
    echo -e "      ${DIM}── Reconnaissance ─────────────────────────────────────${NC}"
    [[ -n "$SHODAN_API_KEY"     ]] && echo -e "      ${G}[OK]${NC} Shodan already set" \
      || { echo -ne "      ${Y}Shodan API key              : ${NC}"; read -r sk; [[ -n "$sk" ]] && SHODAN_API_KEY="$sk"; }
    [[ -n "$SECURITYTRAILS_KEY" ]] && echo -e "      ${G}[OK]${NC} SecurityTrails already set" \
      || { echo -ne "      ${Y}SecurityTrails API key      : ${NC}"; read -r st; [[ -n "$st" ]] && SECURITYTRAILS_KEY="$st"; }

    echo -e "      ${DIM}── Email & Leaks ───────────────────────────────────────${NC}"
    [[ -n "$HUNTER_API_KEY"     ]] && echo -e "      ${G}[OK]${NC} Hunter.io already set" \
      || { echo -ne "      ${Y}Hunter.io API key           : ${NC}"; read -r hk; [[ -n "$hk" ]] && HUNTER_API_KEY="$hk"; }
    [[ -n "$GITHUB_TOKEN"       ]] && echo -e "      ${G}[OK]${NC} GitHub token already set" \
      || { echo -ne "      ${Y}GitHub token (leak search)  : ${NC}"; read -r gt; [[ -n "$gt" ]] && GITHUB_TOKEN="$gt"; }

    echo -e "      ${DIM}── Vulnerability ───────────────────────────────────────${NC}"
    [[ -n "$WPSCAN_API_TOKEN"   ]] && echo -e "      ${G}[OK]${NC} WPScan token already set" \
      || { echo -ne "      ${Y}WPScan API token            : ${NC}"; read -r wt; [[ -n "$wt" ]] && WPSCAN_API_TOKEN="$wt"; }
  fi

  echo ""
  # Resolve IP before drawing box to avoid pause mid-render
  if [[ -n "$DOMAIN" && -z "$IP" ]]; then
    IP=$(dig +short A "$DOMAIN" @1.1.1.1 2>/dev/null | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | head -1 || true)
  fi

  echo -e "${B}┌─────────────────────────────────────────────────────────────┐${NC}"
  echo -e "${B}│${NC}  ${BOLD}Scan Summary${NC}"
  echo -e "${B}├─────────────────────────────────────────────────────────────┤${NC}"
  [[ -n "$DOMAIN" ]] && echo -e "${B}│${NC}  Domain   : ${W}$DOMAIN${NC}"
  if [[ -n "$IP" ]]; then
    echo -e "${B}│${NC}  IP       : ${W}$IP${NC}"
  else
    echo -e "${B}│${NC}  IP       : ${DIM}(resolving during scan)${NC}"
  fi
  $DOMAIN_AUTO_RESOLVED && echo -e "${B}│${NC}  ${DIM}(hostname auto-resolved from IP)${NC}"
  echo -e "${B}│${NC}  Mode     : ${W}$( $QUICK && echo 'Quick (~2 min)' || { $ACTIVE && echo 'Full (passive + active)' || echo 'Passive only'; } )${NC}"
  echo -e "${B}│${NC}  Threads  : ${W}$THREADS${NC}"
  echo -e "${B}└─────────────────────────────────────────────────────────────┘${NC}"

  echo -ne "\n  ${Y}Start scan? [Y/n]: ${NC}"
  echo ""
  read -r confirm
  [[ "${confirm:-Y}" =~ ^[Nn] ]] && echo "Aborted." && exit 0
}

# ================================================================
#  SETUP OUTPUT DIRECTORY
# ================================================================

setup_output() {
  local target="${DOMAIN:-$IP}"
  SCAN_ID="${target}_${TIMESTAMP}"
  # When running as root via sudo, save to the invoking user's home dir
  local base_dir="$HOME"
  if [[ $EUID -eq 0 && -n "${SUDO_USER:-}" ]]; then
    base_dir=$(getent passwd "$SUDO_USER" | cut -d: -f6)
    [[ -z "$base_dir" ]] && base_dir="/home/$SUDO_USER"
  fi
  OUT_DIR="${base_dir}/recon_${SCAN_ID}"
  LOG_FILE="${OUT_DIR}/raw_output.txt"

  mkdir -p "${OUT_DIR}/"{nmap,feroxbuster,dirsearch,ffuf,nuclei,emails,leaks,cve,securitytrails}
  mkdir -p "${OUT_DIR}/js/cache"

  echo "RECONOMEW Scan - Target: ${target} - ${TIMESTAMP}" > "$LOG_FILE"
  info "Output directory: ${W}${OUT_DIR}${NC}"

}
